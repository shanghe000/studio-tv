func TestRequestDiagnosticSurvivesCORSRejectionAndRejectsInjectedID(t *testing.T) {
	var code, rid string
	observe := func(next http.Handler) http.Handler {
		return http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
			next.ServeHTTP(w, r)
			code = ErrorCode(r)
			rid = RequestID(r)
		})
	}
	h := RequestContext(observe(Base([]string{"https://trusted.example"})(http.HandlerFunc(func(http.ResponseWriter, *http.Request) { t.Fatal("untrusted origin reached handler") }))))
	r := httptest.NewRequest("GET", "https://service.example/api/v2/unknown?secret=test-sensitive-value", nil)
	r.Header.Set("Origin", "https://untrusted.example")
	r.Header.Set("X-Request-Id", "test-sensitive-value")
	r.Header.Set("log_id", "test-sensitive-value")
	w := httptest.NewRecorder()
	h.ServeHTTP(w, r)
	if w.Code != 403 || code != "ORIGIN_FORBIDDEN" || rid != w.Header().Get("X-Request-Id") {
		t.Fatal("diagnostic was lost before CORS rejection")
	}
	if _, err := uuid.Parse(rid); err != nil {
		t.Fatal("ID was not generated by the server")
	}
}

func TestUnknownErrorDoesNotLogCredentialsAndRecordsSafeCode(t *testing.T) {
	var output bytes.Buffer
	previous := slog.Default()
	slog.SetDefault(slog.New(slog.NewJSONHandler(&output, nil)))
	defer slog.SetDefault(previous)
	var code string
	h := RequestContext(http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		WriteError(w, r, errors.New("test-sensitive-value https://user:password@example.org?token=private"))
		code = ErrorCode(r)
	}))
	w := httptest.NewRecorder()
	h.ServeHTTP(w, httptest.NewRequest("GET", "/", nil))
	if w.Code != 500 || code != "INTERNAL_ERROR" {
		t.Fatal("unexpected unknown-error projection")
	}
	for _, v := range []string{"test-sensitive-value", "password", "token=private"} {
		if strings.Contains(output.String(), v) || strings.Contains(w.Body.String(), v) {
			t.Fatal("unknown error leaked private detail")
		}
	}
	RequestContext(http.HandlerFunc(func(_ http.ResponseWriter, r *http.Request) {
		RecordError(r, "token=private")
		if ErrorCode(r) != "INTERNAL_ERROR" {
			t.Fatal("unsafe diagnostic code accepted")
		}
	})).ServeHTTP(httptest.NewRecorder(), httptest.NewRequest("GET", "/", nil))
}
